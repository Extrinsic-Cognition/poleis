seal_read() {
  # seal_read <label> <road> <commit> <the exit it must give> <words its line must hold>: once, or until the seal is final (120 s at most)
  n=0
  while :; do
    t0=$(perl -MTime::HiRes=time -e 'printf "%d", time * 1000')
    nice -n 19 "$reader" read "$3" --road "$2" --json > "$work/seal-$1.json" 2> "$work/seal-$1.line"
    rc=$?
    t1=$(perl -MTime::HiRes=time -e 'printf "%d", time * 1000')
    { [ "$rc" = "$4" ] || [ "$4" != 0 ] || [ $n -ge 60 ]; } && break
    n=$((n + 1))
    sleep 2
  done
  line=$(tail -n 1 "$work/seal-$1.line")
  { [ "$rc" = "$4" ] && grep -q "$5" "$work/seal-$1.line"; } || { cat "$work/seal-$1.line"; say "the reader on $1 gave exit $rc, not $4 with \"$5\""; exit 1; }
